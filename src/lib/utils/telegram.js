// ─── Telegram ────────────────────────────────────────────────────────────────
export async function sendTelegram(botToken, chatId, text) {
  const url = `https://api.telegram.org/bot${botToken}/sendMessage`;
  const r = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      chat_id: chatId,
      text,
      parse_mode: 'HTML',
      disable_web_page_preview: false,
    }),
  });
  const d = await r.json();
  if (!d.ok) throw new Error(d.description || 'Telegram error');
  return d;
}

// Helper: Escape HTML special characters to avoid Telegram 400 bad request error
export function escapeHtml(str) {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

export const DEFAULT_TELEGRAM_TEMPLATE = {
  mode: 'standard', // 'compact' | 'standard' | 'detailed'
  showConfidence: true,
  showSummary: true,
  showPracticalTip: true,
  showFunFact: false,
  showSourceLink: true,
  showMatrix: false,
};

export function formatTelegramMessage(cards, language = 'zh', templateOptions = {}) {
  const isZh = language === 'zh';
  const opts = { ...DEFAULT_TELEGRAM_TEMPLATE, ...(templateOptions || {}) };
  const cardList = Array.isArray(cards) ? cards : [];

  const header = isZh
    ? `🔮 <b>CaféPrism 稜咖 研析速報</b>\n📅 ${new Date().toLocaleDateString('zh-TW')}\n\n`
    : `🔮 <b>CaféPrism Digest</b>\n📅 ${new Date().toDateString()}\n\n`;

  const body = cardList.slice(0, 3).map((card, i) => {
    const rawTitle = card.primaryTitle || card.subject || (isZh ? '未命名研究' : 'Untitled Research');
    const title = escapeHtml(rawTitle.slice(0, 80));
    const badge = opts.showConfidence
      ? (card.confidence === 'high' ? '🟢 ' : card.confidence === 'medium' ? '🟡 ' : '🔴 ')
      : '';

    let cardBlock = `${badge}<b>${i + 1}. ${title}</b>`;

    // 核心摘要
    if (opts.showSummary && card.summary) {
      let cleanSummary = card.summary.replace(/<[^>]+>/g, '').trim();
      if (opts.mode === 'compact') {
        const firstSentence = cleanSummary.split(/[。\n.!?]/)[0];
        cleanSummary = (firstSentence ? firstSentence + '。' : cleanSummary.slice(0, 100));
      } else if (opts.mode === 'detailed') {
        cleanSummary = cleanSummary.slice(0, 450);
      } else {
        cleanSummary = cleanSummary.slice(0, 260);
      }
      cardBlock += `\n${escapeHtml(cleanSummary)}`;
    }

    // 咖啡師沖煮實用建議
    if (opts.showPracticalTip && card.practical_tip) {
      const tip = escapeHtml(card.practical_tip.slice(0, 150));
      cardBlock += `\n💡 <i>${isZh ? '實務建議' : 'Tip'}: ${tip}</i>`;
    }

    // 冷知識 / 趣聞
    if (opts.showFunFact && card.fun_fact) {
      const fact = escapeHtml(card.fun_fact.slice(0, 150));
      cardBlock += `\n☕ <i>${isZh ? '冷知識' : 'Fun Fact'}: ${fact}</i>`;
    }

    // 分析矩陣共識與分歧
    if (opts.showMatrix && (card.consensus || card.conflicts)) {
      if (card.consensus) {
        cardBlock += `\n✓ <i>${isZh ? '共識' : 'Consensus'}: ${escapeHtml(card.consensus.slice(0, 120))}</i>`;
      }
      if (card.conflicts) {
        cardBlock += `\n⚠ <i>${isZh ? '分歧' : 'Conflict'}: ${escapeHtml(card.conflicts.slice(0, 120))}</i>`;
      }
    }

    // 原文連結
    if (opts.showSourceLink) {
      const rawLink = card.articles?.[0]?.link || '';
      const safeLink = (/^https?:\/\//i.test(rawLink) ? rawLink : '').replace(/&/g, '&amp;').replace(/"/g, '&quot;');
      if (safeLink) {
        cardBlock += `\n🔗 <a href="${safeLink}">${isZh ? '查看原文' : 'Read source'}</a>`;
      }
    }

    return cardBlock;
  }).join('\n\n─────────────\n\n');

  const footer = isZh
    ? `\n\n<i>由 CaféPrism 稜咖 自動研析推播 · 附三層來源交叉比對</i>`
    : `\n\n<i>Generated by CaféPrism · Verified across sources</i>`;

  return header + body + footer;
}
